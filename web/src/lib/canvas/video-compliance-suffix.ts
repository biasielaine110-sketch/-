/**
 * 铺链路写进视频节点的「合规后缀」（用户 2026-11-11 第 02 条）。
 *
 * 用户原话：「运行脚本生成器，执行第一套方案，并铺链路时，需要给铺出的视频窗口写入的
 * 文本内容 的最后添加如下内容」—— 后面给的是一段固定的禁止项 / 强制声明。
 *
 * 为什么放在「**所有**方案、所有铺链路入口」而不是只给第一套：
 *  - 这段是平台过审的硬约束（禁水印 / 禁字幕 / 只留环境音），跟用哪套分镜表无关；
 *  - 只给第一套的话，用户切到第二套铺完才发现又要手补一遍，是同一个坑第二次踩。
 * 三处入口共用：`handleBuildScriptPipeline`（一键铺链路）、`handleBuildShotVideo`（单镜 / 多选）。
 *
 * ⚠️ 只加在「铺链路建出来的视频节点」上，不动「双击改写提示词」那条链路 ——
 * 用户自己改过的提示词不该被偷偷塞尾巴（重铺一次即会带上）。
 */

/** 原样照抄用户给的四行（半角 , ; ( ) 也不改，模型对这几个符号不敏感，改动反而容易引出歧义）。 */
export const VIDEO_COMPLIANCE_SUFFIX = [
    "【禁止项】",
    "文字/UI/水印/Logo/角标/可读文字/真实UI",
    "【强制声明】",
    "无背景音乐,仅保留环境音与人声和音效;画面禁字幕/文字/水印/Logo;禁止可读文字(指画面字幕文字,不含人声台词)",
].join("\n");

/**
 * 把合规后缀拼到提示词末尾。
 *
 * 幂等：已经带过（含「【强制声明】」）就直接返回原文 —— 重铺 / 合并段拼装时不会叠两遍。
 * 空提示词返回空串（不凭空造一个只有禁止项的提示词）。
 */
export function withVideoComplianceSuffix(prompt: string | null | undefined): string {
    const text = String(prompt ?? "").trim();
    if (!text) return "";
    if (text.includes("【强制声明】") || text.includes("【禁止项】")) return text;
    return `${text}\n\n${VIDEO_COMPLIANCE_SUFFIX}`;
}
